"""Deterministic reviewer-facing summary of frozen evaluation evidence."""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any


def _percentage(value: float | None) -> str:
    return "—" if value is None else f"{100 * value:.1f}%"


def _decimal(value: float | None, digits: int = 3) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _interval(interval: dict[str, Any] | None, *, percentage: bool = False) -> str:
    if not interval:
        return "—"
    lower = float(interval["lower_95"])
    upper = float(interval["upper_95"])
    if percentage:
        return f"{100 * lower:.1f}%–{100 * upper:.1f}%"
    return f"{lower:.3f}–{upper:.3f}"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _headline_comparisons(
    metrics: dict[str, Any], headline_system: str
) -> list[dict[str, Any]]:
    rows = []
    for comparison in metrics["paired_intent_comparisons"]:
        if headline_system not in {comparison["system_a"], comparison["system_b"]}:
            continue
        headline_is_a = comparison["system_a"] == headline_system
        competitor = comparison["system_b"] if headline_is_a else comparison["system_a"]
        for slice_name in ("natural", "challenge", "all"):
            values = comparison["slices"][slice_name]
            point = float(values["macro_f1_difference"])
            lower = float(values["lower_95"])
            upper = float(values["upper_95"])
            if not headline_is_a:
                point, lower, upper = -point, -upper, -lower
            rows.append(
                {
                    "competitor": competitor,
                    "slice": slice_name,
                    "difference": point,
                    "lower_95": lower,
                    "upper_95": upper,
                }
            )
    return rows


def write_evidence_summary(
    *,
    metrics: dict[str, Any],
    annotation_agreement: dict[str, Any],
    retrieval_metrics: dict[str, Any],
    reply_quality: dict[str, Any],
    judge_agreement: dict[str, Any],
    failure_analysis: dict[str, Any],
    offline_trust_gate: dict[str, Any],
    headline_system: str,
    output_path: str | Path,
) -> dict[str, Any]:
    """Write one generated Markdown view without replacing source JSON artifacts."""
    if headline_system not in metrics["systems"]:
        raise ValueError("Evidence summary headline system is absent from metrics")
    lines = [
        "# Frozen evaluation evidence summary",
        "",
        "> Generated by `python -m tescogpt reproduce` from frozen per-example artifacts. ",
        "> Source JSON/CSV files remain authoritative; do not edit this summary manually.",
        "",
        "## Independent annotation agreement",
        "",
        f"Overlap: **{annotation_agreement['overlap_count']} cases**.",
        "",
        "| Field | Raw agreement | Cohen's κ |",
        "|---|---:|---:|",
    ]
    for field in ("intent_label", "handling_label", "reason_code"):
        result = annotation_agreement["fields"][field]
        lines.append(
            f"| {field} | {_percentage(result['raw_agreement'])} | "
            f"{_decimal(result['cohen_kappa'])} |"
        )
    lines.extend(
        [
            "",
            "## Core agent results",
            "",
            "| System | Slice | Intent macro-F1 (95% bootstrap) | Coverage | "
            "Unsafe auto | Wilson upper 95% | Reason accuracy |",
            "|---|---|---:|---:|---:|---:|---:|",
        ]
    )
    for system_name, system in metrics["systems"].items():
        for slice_name in ("natural", "challenge", "all"):
            result = system["slices"][slice_name]
            intent = result["intent"]
            routing = result["routing"]
            display = f"**{system_name}**" if system_name == headline_system else system_name
            unsafe = (
                f"{routing['unsafe_auto_count']}/{routing['auto_handled_count']} "
                f"({_percentage(routing['unsafe_auto_rate_given_auto'])})"
            )
            lines.append(
                f"| {display} | {slice_name} | "
                f"{intent['macro_f1_observed_intents']:.3f} "
                f"({_interval(intent['bootstrap_95'])}) | "
                f"{_percentage(routing['coverage'])} | {unsafe} | "
                f"{_percentage(routing['unsafe_auto_rate_wilson_upper_95'])} | "
                f"{_percentage(result['decision_reason']['exact_accuracy'])} |"
            )
    lines.extend(
        [
            "",
            f"### Paired intent difference: `{headline_system}` minus competitor",
            "",
            "| Competitor | Slice | Macro-F1 difference | Paired 95% interval |",
            "|---|---|---:|---:|",
        ]
    )
    for row in _headline_comparisons(metrics, headline_system):
        lines.append(
            f"| {row['competitor']} | {row['slice']} | {row['difference']:.3f} | "
            f"{row['lower_95']:.3f}–{row['upper_95']:.3f} |"
        )

    lines.extend(
        [
            "",
            "## Pre-registered offline trust gate",
            "",
            f"Result: **{'PASS' if offline_trust_gate['passed'] else 'FAIL'}**; "
            f"recommendation: `{offline_trust_gate['recommendation']}`.",
            "",
            "| Check | Actual | Criterion | Result |",
            "|---|---:|---:|---:|",
        ]
    )
    for check in offline_trust_gate["checks"]:
        actual = "—" if check["actual"] is None else f"{check['actual']:.3f}"
        lines.append(
            f"| {check['name']} | {actual} | {check['criterion']} | "
            f"{'PASS' if check['passed'] else 'FAIL'} |"
        )
    lines.extend(["", offline_trust_gate["scope_limit"]])

    retrieval_systems = retrieval_metrics["systems"]
    retrieval_example = next(iter(retrieval_systems.values()))
    precision_key = next(key for key in retrieval_example if key.startswith("pooled_precision"))
    ndcg_key = next(key for key in retrieval_example if key.startswith("pooled_ndcg"))
    lines.extend(
        [
            "",
            "## Blinded retrieval relevance",
            "",
            "| Retriever | Queries | Pooled precision | Pooled nDCG |",
            "|---|---:|---:|---:|",
        ]
    )
    for system_name, result in retrieval_systems.items():
        lines.append(
            f"| {system_name} | {result['query_count']} | "
            f"{result[precision_key]:.3f} | {result[ndcg_key]:.3f} |"
        )
    retrieval_pair = retrieval_metrics["paired_comparison"]
    lines.extend(
        [
            "",
            "Outcome vs BM25 by query: "
            f"**{retrieval_pair['outcome_wins']} wins / {retrieval_pair['ties']} ties / "
            f"{retrieval_pair['bm25_wins']} losses**; mean nDCG difference "
            f"{retrieval_pair['mean_ndcg_difference_outcome_minus_bm25']:.3f}.",
            "",
            "## System-blinded human reply quality",
            "",
            "| System | Reviewed replies | Pass rate (Wilson 95%) | Critical-error rate | "
            "Mean rubric / 12 |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for system_name, system in reply_quality["systems"].items():
        result = system["slices"]["all"]
        lines.append(
            f"| {system_name} | {result['row_count']} | "
            f"{_percentage(result['overall_pass_rate'])} "
            f"({_interval(result['overall_pass_wilson_95'], percentage=True)}) | "
            f"{_percentage(result['critical_error_rate'])} | "
            f"{_decimal(result['mean_rubric_total_out_of_12'], 2)} |"
        )
    reference = reply_quality["reference_system"]
    lines.extend(
        [
            "",
            f"### Rubric-derived comparison for `{reference}`",
            "",
            "| Competitor | Cases | Reference wins | Ties | Reference losses |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for competitor, comparison in reply_quality["rubric_derived_pairwise"].items():
        lines.append(
            f"| {competitor} | {comparison['case_count']} | "
            f"{comparison['reference_wins']} | {comparison['ties']} | "
            f"{comparison['reference_losses']} |"
        )

    trust_gate = judge_agreement["judge_advisory_trust_gate"]
    lines.extend(
        [
            "",
            "## LLM-judge validation",
            "",
            f"Advisory trust gate: **{'PASS' if trust_gate['passed'] else 'FAIL'}**.",
            "",
            "| Judge run | Rows | Pass accuracy | Pass Cohen's κ | Privacy exact | "
            "Routing exact |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for run_name, comparison in judge_agreement["comparisons"].items():
        lines.append(
            f"| {run_name} | {comparison['row_count']} | "
            f"{_percentage(comparison['overall_pass_accuracy'])} | "
            f"{_decimal(comparison['overall_pass_cohen_kappa'])} | "
            f"{_percentage(comparison['dimensions']['privacy_safety']['exact_agreement'])} | "
            f"{_percentage(comparison['dimensions']['routing_fit']['exact_agreement'])} |"
        )
    if trust_gate["failed_checks"]:
        lines.extend(
            [
                "",
                "Failed trust checks: " + ", ".join(trust_gate["failed_checks"]) + ".",
            ]
        )

    lines.extend(
        [
            "",
            "## Failure evidence",
            "",
            f"The generated ledger contains **{failure_analysis['event_count']} event rows**. "
            "Counts use subsystem-specific denominators and are not a common ranking.",
            "",
            "## Interpretation limits",
            "",
            "- The challenge slice is a stress test, not a production prevalence estimate.",
            "- Zero observed unsafe sends does not imply zero risk; use the Wilson upper bound.",
            "- Retrieval metrics are pooled top-k judgments, so corpus-wide recall is unknown.",
            "- Human reply quality uses the preregistered review sample, not all gold cases.",
            "- The LLM judge is advisory even when its preregistered trust gate passes.",
            "- Failure-event counts from different denominators must not be compared directly.",
        ]
    )
    destination = Path(output_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return {
        "file": destination.name,
        "sha256": _sha256(destination),
        "line_count": len(lines),
        "headline_system": headline_system,
    }
